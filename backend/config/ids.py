import secrets
import time


def make_id(prefix: str) -> str:
    """Строковый первичный ключ вида "ord-1755123456789-a3f1c02e".

    Seed-данные используют порядковые ID ("biz-001"); объекты, создаваемые
    в рантайме, получают метку времени и короткий случайный хвост.

    Хвост обязателен, а не декоративен: одной миллисекунды хватает на
    десятки вызовов подряд, поэтому голая метка времени давала одинаковые
    ключи для двух записей, созданных в одной операции — приём резерва
    пишет два события склада, доставка заказа пишет по одному на позицию.

    Хвост в 4 байта (32 бита), а не 2: с 16-битным хвостом 1000 вызовов
    подряд почти гарантированно дают коллизию (парадокс дней рождения —
    ожидаемо ~7-8 совпадений на 65536 значений), что и подтвердил прогон
    теста. При 32 битах ожидаемое число коллизий на той же выборке — около
    0.0001, что уже не отличимо от нуля.
    """
    return f"{prefix}-{int(time.time() * 1000)}-{secrets.token_hex(4)}"
